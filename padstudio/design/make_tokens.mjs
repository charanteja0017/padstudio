const outputs = [[KT_OUT, kotlin()], [CSS_OUT, css()]];
const rel = (f) => relative(REPO, f);

if (opts.check) {
  const stale = outputs.filter(([f, text]) => !existsSync(f) || readFileSync(f, "utf8") !== text);
  for (const [f] of stale) console.error(`STALE ${rel(f)}: differs from what ${rel(opts.tokens)} generates; run node padstudio/design/make_tokens.mjs`);
  if (stale.length) process.exit(3);
  console.log(`Up to date: ${outputs.map(([f]) => rel(f)).join(", ")}`);
} else if (opts.dryRun) {
  console.log(`Dry run: nothing written (${outputs.map(([f, t]) => `${rel(f)} ${Buffer.byteLength(t)} bytes`).join(", ")}).`);
} else {
  for (const [f, text] of outputs) {
    if (existsSync(f) && readFileSync(f, "utf8") === text) { console.log(`unchanged ${rel(f)}`); continue; }
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, text);
    console.log(`wrote ${rel(f)} (${Buffer.byteLength(text)} bytes)`);
  }
}
