function css() {
  const L = [];
  L.push(
    `/* ${HEADER} */`,
    "/* Design tokens for the PadStudio 2 preview (docs/redesign/BRIEF.md, \"Token contract\"). Colours are",
    "   selected by data-palette and data-theme on the mock frame, for example",
    "   <div data-palette=\"Violet\" data-theme=\"dark\">. Sizes are px with 1 dp = 1 px inside the frame. */",
    "",
    ":root {",
    "  /* Type scale at font scale 1.0; fontscale.js rewrites the sizes for other scales. */",
  );
  for (const [k, v] of typeRoles) L.push(`  --t-${kebab(k)}-size: ${v.size}px;`, `  --t-${kebab(k)}-line: ${v.line}px;`);
  L.push("  /* Weights: body regular, titles medium, never above 600 (Bold text adds 300). */");
  for (const [k, v] of entries(tokens.weight)) L.push(`  --w-${kebab(k)}: ${v};`);
  L.push("  /* Corner radii. */");
  for (const [k, v] of entries(tokens.corner)) L.push(`  --r-${kebab(k)}: ${v}px;`);
  L.push(`  /* Spacing, all on the ${unit} dp grid; touch-target is the minimum size of anything tappable. */`);
  for (const [k, v] of entries(tokens.space)) L.push(`  --s-${kebab(k)}: ${v}px;`);
  L.push("}");
  for (const s of schemes) {
    L.push("", `[data-palette="${s.name}"][data-theme="${s.theme}"] {`, `  color-scheme: ${s.theme};`);
    for (const r of CSS_CONTRACT) L.push(`  --${kebab(r)}: ${s.c[r]};`);
    for (const k of SEMANTIC) L.push(`  --${k}: ${s.c[k]};`);
    L.push("  /* Status icons and labels; the base colours above are for tints and fills: */");
    for (const k of SEMANTIC) L.push(`  --${k}-ink: ${s.c[inkKey(k)]};`);
    L.push("  /* Also in the app's ColorScheme, though not in the contract: */");
    for (const r of CSS_EXTRA) L.push(`  --${kebab(r)}: ${s.c[r]};`);
    L.push("}");
  }
  L.push("");
  return L.join("\n");
}

