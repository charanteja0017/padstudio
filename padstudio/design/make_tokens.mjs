const KT_OUT = join(HERE, "../app/src/main/kotlin/com/charan/padstudio/ui/theme/Tokens.kt");
const CSS_OUT = join(REPO, "docs/redesign/tokens.css");
const HEADER = "Generated by padstudio/design/make_tokens.mjs — edit padstudio/design/tokens.json, not this file.";
const MCU_VERSION = "0.3.0";

