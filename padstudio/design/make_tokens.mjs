// PadStudio design tokens (redesign plan §3.1, §3.6). Reads tokens.json and writes:
//   padstudio/app/src/main/kotlin/com/charan/padstudio/ui/theme/Tokens.kt   for the app
//   docs/redesign/tokens.css                                                 for the HTML preview
//
// Colours use WiFiBar's method (WIFI widget/Branding/make_android_colors.mjs) with Google's
// material-color-utilities 0.3.0, pinned because 0.4.0 has a broken ESM import:
//   - primary and secondary: SchemeFidelity from the palette's seed;
//   - tertiary: the hue and chroma of a second colour (the logo palette's glow);
//   - neutrals: the hue of #F5F5F7 at very low chroma; neutral variant: the seed's hue at chroma 6;
//   - background and surface pinned to #F5F5F7 / #1C1C1E, with a hand-spaced surface-container ladder.
//
// Before writing anything it checks WCAG 2 contrast for every scheme (plan §13 "Contrast") and prints the
// table: text pairs at 4.5, primary titles at 3.0, and each semantic ink (status icons and labels) at 3.0 on
// its theme's background, surface and surface containers. If any pair fails, or a token breaks a house
// rule, it writes nothing and exits 1.
//
// Usage (node 22, from any directory):
//   npm ci --prefix padstudio/design                  once; installs exactly what package-lock.json pins
//   node padstudio/design/make_tokens.mjs             check, then write both files (only if they changed)
//   node padstudio/design/make_tokens.mjs --check     check, then exit 3 if either file is out of date
//   node padstudio/design/make_tokens.mjs --tokens <file.json> --dry-run   try other tokens, write nothing
//
// Exit codes: 0 ok; 1 contrast gate or token rule failed (nothing written); 2 usage, setup or input
// error; 3 --check found an output that differs from what tokens.json generates.

