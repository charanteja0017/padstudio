const USAGE = "usage: node make_tokens.mjs [--check] [--dry-run] [--tokens <file.json>]";
const opts = { check: false, dryRun: false, tokens: join(HERE, "tokens.json") };
for (let i = 2; i < process.argv.length; i++) {
  const a = process.argv[i];
  if (a === "--check") opts.check = true;
  else if (a === "--dry-run") opts.dryRun = true;
  else if (a === "--tokens" && i + 1 < process.argv.length) opts.tokens = resolve(process.argv[++i]);
  else if (a === "--help" || a === "-h") { console.log(USAGE); process.exit(0); }
  else { console.error(`make_tokens: unknown argument ${a}\n${USAGE}`); process.exit(2); }
}

