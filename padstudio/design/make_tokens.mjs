// Kotlin

const ENUM = (name) => name.toUpperCase();
const lowerFirst = (s) => s[0].toLowerCase() + s.slice(1);
const ktColor = (h) => `Color(0xFF${h.slice(1)})`;
const ktSchemeName = (s) => `${lowerFirst(s.name)}${cap(s.theme)}`;

function kotlin() {
  const L = [];
  L.push(`// ${HEADER}`, "", "package com.charan.padstudio.ui.theme", "");
  L.push(
    "import androidx.compose.material3.ColorScheme",
    "import androidx.compose.material3.darkColorScheme",
    "import androidx.compose.material3.lightColorScheme",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.text.font.FontWeight",
    "import androidx.compose.ui.unit.Dp",
    "import androidx.compose.ui.unit.TextUnit",
    "import androidx.compose.ui.unit.dp",
    "import androidx.compose.ui.unit.sp",
    "",
  );
  L.push(
    "/**",
    " * PadStudio's brand palettes (plan §3.1). [Tokens] gives each a light and a dark [ColorScheme]. The seed",
    " * and tertiary source are the logo palette's gradient top and glow.",
    " */",
    "enum class BrandPalette {",
  );
  for (const [name, p] of palettes) {
    L.push(`    /** Seed ${p.seed.toUpperCase()}; tertiary from ${p.tertiary.toUpperCase()}. */`);
    L.push(`    ${ENUM(name)},`);
  }
  L.push("}", "");
  L.push(
    "/**",
    " * Design tokens shared with the HTML preview (docs/redesign/tokens.css): a colour scheme per",
    " * [BrandPalette] and theme, semantic colours, the type scale, weights, corner radii and spacing.",
    " *",
    " * Colours come from Material 3's SchemeFidelity on each seed (material-color-utilities 0.3.0), with",
    ` * background and surface pinned to ${surfaces.light.surface} (light) and ${surfaces.dark.surface} (dark). The generator checks`,
    " * WCAG contrast for every scheme before it writes this file.",
    " */",
    "object Tokens {",
    "    /** The palette the app uses until the logo pick chooses another (plan §3.1). */",
    `    val DefaultPalette: BrandPalette = BrandPalette.${ENUM(colour.defaultPalette)}`,
    "",
  );
  for (const theme of ["light", "dark"]) {
    L.push(`    /** The ${theme} scheme for [p], with all ${ROLES.length} Material 3 colour roles set. */`);
    L.push(`    fun ${theme}Scheme(p: BrandPalette): ColorScheme = when (p) {`);
    for (const s of schemes.filter((x) => x.theme === theme)) L.push(`        BrandPalette.${ENUM(s.name)} -> ${ktSchemeName(s)}`);
    L.push("    }", "");
  }
  L.push(
    "    // Semantic colours, separate from the brand. These bases are for tints and fills, the same in both themes;",
    "    // status icons and labels use the inks below.",
  );
  for (const k of SEMANTIC) {
    const v = semantic[k];
    if (HEX.test(v)) L.push(`    val ${cap(k)}: Color = ${ktColor(v.toUpperCase())}`);
    else L.push(`    // ${cap(k)} is each scheme's own ${v} colour: use MaterialTheme.colorScheme.${v}.`);
  }
  L.push(
    "",
    "    // Inks: status icons and short status labels. Each reaches 3:1 on its theme's background, surface and",
    "    // surface containers (the generator checks). A theme without its own ink in tokens.json uses the base.",
  );
  for (const k of SEMANTIC) {
    const [light, dark] = THEMES.map((t) => inkSource(k, t));
    if (HEX.test(light) && HEX.test(dark)) {
      L.push(`    val ${cap(k)}InkLight: Color = ${ktColor(light.toUpperCase())}`);
      L.push(`    val ${cap(k)}InkDark: Color = ${ktColor(dark.toUpperCase())}`);
      L.push(`    fun ${k}Ink(dark: Boolean): Color = if (dark) ${cap(k)}InkDark else ${cap(k)}InkLight`);
    } else {
      L.push(`    // ${cap(k)}'s ink is each scheme's own ${light} colour: use MaterialTheme.colorScheme.${light}.`);
    }
  }
  L.push("", "    // Type scale in sp at font scale 1.0: size and line height. Android scales sp nonlinearly above 1.0.");
  for (const [k, v] of typeRoles) {
    L.push(`    val ${cap(k)}Size: TextUnit = ${v.size}.sp`);
    L.push(`    val ${cap(k)}LineHeight: TextUnit = ${v.line}.sp`);
  }
  L.push("", "    // Weights: body regular, titles medium, never above 600, because Android's Bold text adds 300.");
  for (const [k, v] of entries(tokens.weight)) L.push(`    val Weight${cap(k)}: FontWeight = FontWeight(${v})`);
  L.push("", "    // Corner radii. CornerFull makes a pill: Compose clamps a radius to half the shorter side.");
  for (const [k, v] of entries(tokens.corner)) L.push(`    val Corner${cap(k)}: Dp = ${v}.dp`);
  L.push("", `    // Spacing, all on the ${unit} dp grid. TouchTarget is the minimum size of anything tappable.`);
  for (const [k, v] of entries(tokens.space)) L.push(`    val ${cap(k)}: Dp = ${v}.dp`);
  for (const s of schemes) {
    L.push("", `    private val ${ktSchemeName(s)}: ColorScheme = ${s.theme}ColorScheme(`);
    for (const r of ROLES) L.push(`        ${r} = ${ktColor(s.c[r])},`);
    L.push("    )");
  }
  L.push("}", "");
  return L.join("\n");
}

