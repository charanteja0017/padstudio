#!/usr/bin/env python3
"""PadStudio's launcher icon, generated from one set of shapes.

The mark is a "P": its bowl is a tablet with a landscape screen cut out, its stem is a pen whose
nib (amber tip) sits below a ferrule gap. Writes the adaptive-icon layers as Android vector
drawables, and an SVG preview (squircle mask, themed version, small sizes) for checking by eye.

  python3 -I tools/lib/make_logo.py <res dir> <preview.svg>
"""

import math
import sys
from pathlib import Path

VIEW = 108                      # adaptive icon canvas (dp)
SAFE_R = 34.0                   # mark reach from centre; only rounded corners and the nib point pass Android's 33
OPTICAL_DY = 1.0                # the heavy bowl makes a centred mark look high
BG_FROM, BG_TO = "#4338CA", "#7C3AED"
INK, NIB = "#FFFFFF", "#FBBF24"

# Mark in its own units: stem 12 wide, bowl 42 x 34 with corner radius 10, screen 20 x 14 (3:2-ish).
STEM_W, BOWL_W, BOWL_H, R = 12.0, 42.0, 34.0, 10.0
SCREEN = (12.0, 10.0, 32.0, 24.0, 3.0)        # x0, y0, x1, y1, radius
STEM_BOTTOM, GAP = 46.0, 3.0
NIB_TOP = STEM_BOTTOM + GAP
NIB_SHOULDER, NIB_TIP = NIB_TOP + 4.0, NIB_TOP + 13.0
HEIGHT = NIB_TIP


def fit():
    """Scale and offset placing the mark's bounding box centre on the canvas centre within SAFE_R."""
    corners = [(0, R * (1 - math.sqrt(0.5))), (BOWL_W, R * (1 - math.sqrt(0.5))), (0, NIB_SHOULDER), (STEM_W / 2, NIB_TIP), (BOWL_W, BOWL_H - R * (1 - math.sqrt(0.5)))]
    cx, cy = BOWL_W / 2, HEIGHT / 2
    reach = max(math.hypot(x - cx, y - cy) for x, y in corners)
    scale = SAFE_R / reach
    return scale, VIEW / 2 - cx * scale, VIEW / 2 - cy * scale + OPTICAL_DY


S, OX, OY = fit()


def p(x, y):
    return f"{OX + x * S:.2f},{OY + y * S:.2f}"


def r(v):
    return f"{v * S:.2f}"


def body_path():
    """Bowl + stem as one outline, the screen cut out (even-odd)."""
    return " ".join([
        f"M{p(R, 0)}", f"H{OX + (BOWL_W - R) * S:.2f}",
        f"A{r(R)},{r(R)} 0 0 1 {p(BOWL_W, R)}",
        f"V{OY + (BOWL_H - R) * S:.2f}",
        f"A{r(R)},{r(R)} 0 0 1 {p(BOWL_W - R, BOWL_H)}",
        f"H{OX + STEM_W * S:.2f}",
        f"V{OY + (STEM_BOTTOM - 2) * S:.2f}",
        f"A{r(2)},{r(2)} 0 0 1 {p(STEM_W - 2, STEM_BOTTOM)}",
        f"H{OX + 2 * S:.2f}",
        f"A{r(2)},{r(2)} 0 0 1 {p(0, STEM_BOTTOM - 2)}",
        f"V{OY + R * S:.2f}",
        f"A{r(R)},{r(R)} 0 0 1 {p(R, 0)}", "Z",
        screen_path(),
    ])


def screen_path():
    x0, y0, x1, y1, sr = SCREEN
    return " ".join([
        f"M{p(x0 + sr, y0)}", f"H{OX + (x1 - sr) * S:.2f}", f"A{r(sr)},{r(sr)} 0 0 1 {p(x1, y0 + sr)}",
        f"V{OY + (y1 - sr) * S:.2f}", f"A{r(sr)},{r(sr)} 0 0 1 {p(x1 - sr, y1)}",
        f"H{OX + (x0 + sr) * S:.2f}", f"A{r(sr)},{r(sr)} 0 0 1 {p(x0, y1 - sr)}",
        f"V{OY + (y0 + sr) * S:.2f}", f"A{r(sr)},{r(sr)} 0 0 1 {p(x0 + sr, y0)}", "Z",
    ])


def nib_path():
    """Pen nib: full width under the gap, shoulders, then a point."""
    return " ".join([
        f"M{p(0, NIB_TOP + 1)}", f"A{r(1)},{r(1)} 0 0 1 {p(1, NIB_TOP)}", f"H{OX + (STEM_W - 1) * S:.2f}",
        f"A{r(1)},{r(1)} 0 0 1 {p(STEM_W, NIB_TOP + 1)}", f"V{OY + NIB_SHOULDER * S:.2f}",
        f"L{p(STEM_W / 2, NIB_TIP)}", f"L{p(0, NIB_SHOULDER)}", "Z",
    ])


def nib_tip_path():
    """The amber tip: the lower part of the nib."""
    t = 0.45  # how far down the taper the colour starts
    y = NIB_SHOULDER + (NIB_TIP - NIB_SHOULDER) * t
    half = (STEM_W / 2) * (1 - t)
    return f"M{p(STEM_W / 2 - half, y)} L{p(STEM_W / 2 + half, y)} L{p(STEM_W / 2, NIB_TIP)} Z"


def vector(paths):
    body = "\n".join(
        f'    <path\n        android:fillColor="{color}"\n        android:fillType="evenOdd"\n        android:pathData="{d}" />'
        for color, d in paths
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/lib/make_logo.py; edit the script, not this file. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{VIEW}dp"\n    android:height="{VIEW}dp"\n'
        f'    android:viewportWidth="{VIEW}"\n    android:viewportHeight="{VIEW}">\n{body}\n</vector>\n'
    )


def background():
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by tools/lib/make_logo.py; edit the script, not this file. -->\n"
        '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
        f'    <gradient android:angle="315" android:startColor="{BG_FROM}" android:endColor="{BG_TO}" />\n'
        "</shape>\n"
    )


def preview():
    """Launcher-like squircle at 3 sizes, plus the themed (monochrome) version."""
    def icon(x, y, size, themed=False):
        k = size / VIEW
        plate = "#E8E8EE" if themed else "url(#bg)"
        ink = "#3B3B46" if themed else INK
        tip = ink if themed else NIB
        return (
            f'<g transform="translate({x},{y}) scale({k})">'
            f'<rect x="0" y="0" width="{VIEW}" height="{VIEW}" rx="{VIEW * 0.24}" fill="{plate}"/>'
            f'<path d="{body_path()}" fill="{ink}" fill-rule="evenodd"/>'
            f'<path d="{nib_path()}" fill="{ink}"/>'
            f'<path d="{nib_tip_path()}" fill="{tip}"/>'
            f'<circle cx="54" cy="54" r="33" fill="none" stroke="#ff000044" stroke-width="0.4"/></g>'
        )
    w, h = 900, 380
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">'
        f'<defs><linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="{BG_FROM}"/>'
        f'<stop offset="1" stop-color="{BG_TO}"/></linearGradient></defs>'
        f'<rect width="{w}" height="{h}" fill="#D9C3C3"/>'
        + icon(20, 20, 320) + icon(370, 20, 160) + icon(370, 200, 160, themed=True) + icon(560, 20, 96) + icon(680, 20, 48)
        + icon(560, 140, 96, themed=True) + icon(680, 140, 48, themed=True) + "</svg>"
    )


def main() -> int:
    res, preview_svg = Path(sys.argv[1]), Path(sys.argv[2])
    (res / "drawable").mkdir(parents=True, exist_ok=True)
    (res / "drawable/ic_launcher_foreground.xml").write_text(vector([(INK, body_path()), (INK, nib_path()), (NIB, nib_tip_path())]))
    (res / "drawable/ic_launcher_monochrome.xml").write_text(vector([(INK, body_path()), (INK, nib_path())]))
    (res / "drawable/ic_launcher_background.xml").write_text(background())
    preview_svg.write_text(preview())
    print(f"scale {S:.3f}, offset {OX:.2f},{OY:.2f}; wrote layers to {res}/drawable and {preview_svg}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
